type fixture struct {
	OracleCommit string            `json:"oracle_commit"`
	GeneratedBy  string            `json:"generated_by"`
	SourceDigest string            `json:"source_digest"`
	VectorCount  int               `json:"vector_count"`
	Comparison   map[string]string `json:"comparison"`
	Vectors      []vector          `json:"vectors"`
}

func main() {
	out := flag.String("out", "port/fixtures/fetch/static.json", "fixture path")
	check := flag.Bool("check", false, "compare regenerated bytes with the committed fixture")
	flag.Parse()
	result := generate()
	data, err := json.MarshalIndent(result, "", "  ")
	if err != nil {
		panic(err)
	}
	data = append(data, '\n')
	if *check {
		existing, err := os.ReadFile(*out)
		if err != nil {
			panic(fmt.Errorf("read fixture: %w", err))
		}
		if !bytes.Equal(existing, data) {
			panic(fmt.Sprintf("fixture drift: regenerate %s deliberately", *out))
		}
		fmt.Printf("checked %s (%d vectors, source %s)\n", *out, result.VectorCount, result.SourceDigest)
		return
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(*out, data, 0644); err != nil {
		panic(err)
	}
	fmt.Printf("wrote %s (%d vectors, source %s)\n", *out, result.VectorCount, result.SourceDigest)
}

