func trackedPipelineInputs() []struct {
	name, html, query string
	topK              int
} {
	entries, err := os.ReadDir("internal/fetch/pipeline/testdata")
	if err != nil {
		panic(err)
	}
	queries := map[string]struct {
		query string
		topK  int
	}{
		"news_article.html": {query: "mars", topK: 1},
		"nav_heavy.html":    {query: "energy", topK: 1},
		"nextjs_shell.html": {query: "page", topK: 1},
		"form_page.html":    {query: "name", topK: 1},
		"spa_shell.html":    {query: "", topK: 0},
		"spa_shell.md":      {query: "", topK: 0},
	}
	inputs := make([]struct {
		name, html, query string
		topK              int
	}, 0, len(entries))
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		data, err := os.ReadFile(filepath.Join("internal/fetch/pipeline/testdata", name))
		if err != nil {
			panic(err)
		}
		caseConfig := queries[name]
		inputs = append(inputs, struct {
			name, html, query string
			topK              int
		}{
			name: name, html: string(data), query: caseConfig.query, topK: caseConfig.topK,
		})
	}
	return inputs
}

func sourceDigest() string {
	hash := sha256.New()
	for _, path := range sourceFiles {
		data, err := os.ReadFile(path)
		if err != nil {
			panic(err)
		}
		hash.Write([]byte(path))
		hash.Write([]byte{0})
		hash.Write(data)
		hash.Write([]byte{0})
	}
	return hex.EncodeToString(hash.Sum(nil))
}

// canonicalizeInteractiveAttributes removes Go map-iteration nondeterminism from
// the oracle's interactive-element suffixes before the fixture is frozen.
func canonicalizeInteractiveAttributes(markdown string) string {
	lines := strings.Split(markdown, "\n")
	for i, line := range lines {
		if !strings.HasPrefix(line, "- **") {
			continue
		}
		if typeStart := strings.Index(line, " ("); typeStart >= 0 {
			if placeholderStart := strings.Index(line, " ["); placeholderStart > typeStart {
				placeholderEnd := strings.Index(line[placeholderStart:], "]")
				typeEnd := strings.Index(line[typeStart:], ")")
				if placeholderEnd > 0 && typeEnd > 0 {
					placeholderEnd += placeholderStart
					typeEnd += typeStart
					placeholder := line[placeholderStart : placeholderEnd+1]
					kind := line[typeStart : typeEnd+1]
					line = line[:typeStart] + placeholder + kind + line[placeholderEnd+1:]
				}
			}
		}
		lines[i] = line
	}
	return strings.Join(lines, "\n")
}

func makeVector(name, source, query string, topK int) vector {
	tree, err := dom.Parse([]byte(source))
	if err != nil {
		panic(err)
	}
	rawIslands := semantic.ExtractIslands(tree.Root, 1<<20)
	dom.Filter(tree.Root)
	var clean []byte
	if err := html.Render(writer{&clean}, tree.Root); err != nil {
		panic(err)
	}
	best := semantic.BestBlock(tree.Root, 20)
	doc := &agentdom.Document{URL: "https://example.com/source", Title: tree.Title, Lang: tree.Lang}
	builder := agentdom.NewBuilder(0)
	builder.Build(best, doc)
	for _, island := range rawIslands {
		doc.Islands = append(doc.Islands, agentdom.DataIsland{Source: island.Source, JSON: island.JSON})
	}
	markdown, err := render.Markdown(doc, best, true)
	if err != nil {
		panic(err)
	}
	markdown = canonicalizeInteractiveAttributes(markdown)
	sections := relevance.SplitMarkdownSections(markdown)
	ranked := relevance.RankSections(query, sections, topK)
	headings := make([]string, 0, len(ranked))
	for _, section := range ranked {
		headings = append(headings, section.Heading)
	}
	encoded, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		panic(err)
	}
	return vector{Name: name, HTML: source, Query: query, TopK: topK, Title: tree.Title, Lang: tree.Lang, CleanHTML: string(clean), Markdown: markdown, Document: encoded, RankedHeadings: headings}
}

type writer struct{ p *[]byte }

func (w writer) Write(p []byte) (int, error) { *w.p = append(*w.p, p...); return len(p), nil }
